"""sshleash audit: who can use your SSH agent right now?"""
from __future__ import annotations

import glob
import os
import re
import socket
import sys
from dataclasses import dataclass, field

from . import wire

TOOL_MARKERS = {
    "devpod": "DevPod", "docker": "Docker", "orbstack": "OrbStack", "coder": "Coder",
    "gitpod": "Gitpod", "codespace": "GitHub Codespaces", "vscode": "VS Code", "jetbrains": "JetBrains",
    "colima": "Colima", "lima": "Lima", "vagrant": "Vagrant", "tailscale": "Tailscale", "teleport": "Teleport",
    "codex": "Codex", "chatgpt": "ChatGPT", "openai": "OpenAI", "claude": "Claude", "cursor": "Cursor",
    "added by": "a tool", "managed by": "a tool", "generated by": "a tool", "do not edit": "a tool",
}
AGENT_PROCS = re.compile(r"^(codex|claude|cursor|chatgpt|copilot|aider|gemini|opencode|goose|amp|windsurf|sbx|"
                         r"com\.docker|docker|devpod|code|cline)", re.I)
SEV_ORDER = {"high": 0, "medium": 1, "low": 2, "info": 3}


@dataclass
class Finding:
    severity: str
    code: str
    message: str
    where: str = ""
    fix: str = ""

    def as_dict(self):
        return self.__dict__.copy()


@dataclass
class ConfigEntry:
    file: str
    line: int
    patterns: list
    value: str
    comment: str = ""


@dataclass
class SSHConfig:
    forward_agent: list = field(default_factory=list)
    identity_agent: list = field(default_factory=list)
    hostnames: set = field(default_factory=set)
    files: list = field(default_factory=list)


_KV = re.compile(r"^\s*([A-Za-z][A-Za-z0-9]*)\s*(?:=\s*|\s+)(.*?)\s*$")


def parse_ssh_config(path: str, cfg: SSHConfig | None = None, depth: int = 0, base: str | None = None) -> SSHConfig:
    cfg = cfg or SSHConfig()
    path = os.path.expanduser(path)
    base = base or os.path.dirname(path)
    if depth > 8 or path in cfg.files:
        return cfg
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            lines = f.readlines()
    except OSError:
        return cfg
    cfg.files.append(path)
    patterns = ["*"]  # top of file: applies to every host
    block_comment = ""
    recent_comments: list[str] = []
    for no, raw in enumerate(lines, 1):
        s = raw.strip()
        if not s:
            recent_comments = []
            continue
        if s.startswith("#"):
            recent_comments.append(s.lstrip("#").strip())
            continue
        m = _KV.match(s)
        if not m:
            continue
        key, val = m.group(1).lower(), m.group(2)
        val = val.split(" #", 1)[0].strip().strip('"')
        if key in ("host", "match"):
            patterns = val.split() if key == "host" else [f"Match {val}"]
            block_comment = " ".join(recent_comments)
            for p in patterns:
                if not any(c in p for c in "*?!") and not p.startswith("Match"):
                    cfg.hostnames.add(p)
        elif key == "include":
            for inc in val.split():
                inc = os.path.expanduser(inc)
                if not os.path.isabs(inc):
                    inc = os.path.join(base, inc)
                for f in sorted(glob.glob(inc)):
                    parse_ssh_config(f, cfg, depth + 1, base)
        elif key == "hostname":
            cfg.hostnames.add(val)
        elif key == "forwardagent":
            cfg.forward_agent.append(ConfigEntry(path, no, patterns, val, block_comment))
        elif key == "identityagent":
            cfg.identity_agent.append(ConfigEntry(path, no, patterns, val, block_comment))
        recent_comments = []
    return cfg


def _tool(entry: ConfigEntry) -> str:
    text = (entry.comment + " " + " ".join(entry.patterns) + " " + entry.file).lower()
    for marker, name in TOOL_MARKERS.items():
        if marker in text:
            return name
    return ""


def _is_leash(value: str, leash_socket: str) -> bool:
    v = os.path.expanduser(value.strip('"'))
    return "sshleash" in v or os.path.abspath(v) == os.path.abspath(os.path.expanduser(leash_socket))


def check_config(cfg: SSHConfig, leash_socket: str) -> list[Finding]:
    out = []
    for e in cfg.forward_agent:
        v = e.value.lower()
        where = f"{e.file}:{e.line}"
        hosts = " ".join(e.patterns)
        if v == "no":
            continue
        if v != "yes" and _is_leash(e.value, leash_socket):
            out.append(Finding("info", "forward-leashed", f"Host {hosts}: forwards the sshleash socket, so every "
                               "signature there goes through your policy", where))
            continue
        tool = _tool(e)
        wildcard = any(any(c in p for c in "*?") for p in e.patterns) or e.patterns[0].startswith("Match")
        target = "your whole agent" if v == "yes" else f"agent socket {e.value}"
        fix = f"ForwardAgent {leash_socket}   # forward the filtered socket instead"
        if wildcard:
            out.append(Finding("high", "forward-wildcard",
                               f"Host {hosts}: ForwardAgent {e.value} hands {target} to every matching host"
                               + (f" (written by {tool})" if tool else ""), where, fix))
        elif tool:
            out.append(Finding("medium", "forward-tool",
                               f"Host {hosts}: {tool} turned on agent forwarding; anything running there "
                               f"(including AI agents) can sign with your keys", where, fix))
        else:
            out.append(Finding("medium", "forward-host",
                               f"Host {hosts}: ForwardAgent {e.value}; root and every process of your user "
                               "on that host can use your keys while you are connected", where, fix))
    return out


def list_keys(sock_path: str, timeout: float = 3.0) -> list[tuple[bytes, str]] | None:
    try:
        s = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        s.settimeout(timeout)
        s.connect(sock_path)
        s.sendall(wire.frame(wire.REQUEST_IDENTITIES))
        head = _recv(s, 4)
        body = _recv(s, int.from_bytes(head, "big"))
        s.close()
    except OSError:
        return None
    if not body or body[0] != wire.IDENTITIES_ANSWER:
        return None
    return wire.parse_identities(body[1:])


def _recv(s, n):
    buf = b""
    while len(buf) < n:
        chunk = s.recv(n - len(buf))
        if not chunk:
            raise OSError("agent closed the connection")
        buf += chunk
    return buf


def check_agent(env: dict, leash_socket: str) -> tuple[list[Finding], list[dict]]:
    out, keys_out = [], []
    sock = env.get("SSH_AUTH_SOCK")
    if not sock:
        out.append(Finding("info", "no-agent", "SSH_AUTH_SOCK is not set in this shell"))
        return out, keys_out
    leashed = _is_leash(sock, leash_socket)
    keys = list_keys(sock)
    if keys is None:
        out.append(Finding("low", "agent-unreachable", f"SSH_AUTH_SOCK={sock} does not answer"))
        return out, keys_out
    for blob, comment in keys:
        t = wire.key_type(blob)
        keys_out.append({"fingerprint": wire.fingerprint(blob), "type": wire.short_type(blob), "comment": comment,
                         "hardware": t.startswith("sk-")})
    if env.get("SSH_CONNECTION") and not leashed:
        out.append(Finding("medium", "remote-forwarded-agent",
                           f"You are on a remote machine and SSH_AUTH_SOCK={sock} is a forwarded agent with "
                           f"{len(keys)} key(s): root and every process of your user here can sign with them",
                           fix="disconnect agent forwarding, or forward the sshleash socket from your laptop"))
    elif not leashed and keys:
        soft = [k for k in keys_out if not k["hardware"]]
        out.append(Finding("low" if not soft else "medium", "agent-unfiltered",
                           f"SSH_AUTH_SOCK points at an unfiltered agent holding {len(keys)} key(s) "
                           f"({len(soft)} usable without a touch); any process that inherits it can use all of them",
                           where=sock, fix="sshleash run, then use its socket for forwarding / untrusted programs"))
    else:
        out.append(Finding("info", "agent-leashed", f"SSH_AUTH_SOCK is the sshleash socket ({len(keys)} key(s) visible)"))
    return out, keys_out


def scan_processes(real_socks: set[str]) -> list[dict]:
    """Processes of this user that hold SSH_AUTH_SOCK in their environment (Linux)."""
    if not sys.platform.startswith("linux"):
        return []
    me = os.getpid()
    uid = os.getuid()
    found = []
    for d in glob.glob("/proc/[0-9]*"):
        pid = int(d.rsplit("/", 1)[1])
        if pid == me:
            continue
        try:
            if os.stat(d).st_uid != uid:
                continue
            with open(f"{d}/environ", "rb") as f:
                env = f.read().split(b"\0")
            with open(f"{d}/comm") as f:
                name = f.read().strip()
        except OSError:
            continue
        for kv in env:
            if kv.startswith(b"SSH_AUTH_SOCK="):
                val = kv.split(b"=", 1)[1].decode(errors="replace")
                found.append({"pid": pid, "name": name, "socket": val, "real_agent": val in real_socks})
    return found


def run(config_paths: list[str], env: dict, leash_socket: str, processes: bool = True) -> dict:
    cfg = SSHConfig()
    for p in config_paths:
        parse_ssh_config(p, cfg)
    findings = check_config(cfg, leash_socket)
    agent_findings, keys = check_agent(env, leash_socket)
    findings += agent_findings
    procs = []
    sock = env.get("SSH_AUTH_SOCK")
    if processes and sock and not _is_leash(sock, leash_socket):
        procs = [p for p in scan_processes({sock}) if p["real_agent"]]
        agents = sorted({p["name"] for p in procs if AGENT_PROCS.match(p["name"])})
        if agents:
            findings.append(Finding("medium", "agents-hold-socket",
                                    "These running programs can sign with your keys right now: " + ", ".join(agents),
                                    fix="start them with SSH_AUTH_SOCK pointing at sshleash (or unset it)"))
    findings.sort(key=lambda f: SEV_ORDER.get(f.severity, 9))
    return {"files": cfg.files, "findings": [f.as_dict() for f in findings], "keys": keys,
            "processes": procs}
